class AddNonResaoningStepTap(GenerateVerificationDatasetTap):
    generation_seed: str = "selected"


def main():
    args = AddNonResaoningStepTap().parse_args()

    print("Running add_non_reasoning_steps.py...")

    cot_type = "no_cot"
    suffix = "step_merged"

    for split in splits_list[::-1]:
        print(f"Processing {args.dataset_name} {args.model_name} {split}...")

        # load original error labels
        error_labels_path = get_error_labels_path(
            dataset_name=args.dataset_name, model_name=args.model_name,
            split=split, seed=args.generation_seed
        ).with_suffix(f".{cot_type}.{suffix}.jsonl")

        with open(error_labels_path, "r") as f:
            original_error_label_instances = [
                json.loads(line) for line in f
            ]

        updated_error_label_instances = []
        for d in original_error_label_instances:
            # only for formal logic
            if args.dataset_name == "fldx2_symbol":

                # add hypothesis declaration in 50% of the cases
                if random.Random("hypothesis" + d["id"]).random() < 0.5:
                    hypotehsis_template = random.Random(
                        "select hypotehsis declaration" + d["id"]).choice(
                        hypothesis_declaration
                    )

                    # in 75% of cases, we use the true hypothesis
                    if random.Random("true" + d["id"]).random() < 0.75:
                        hypothesis = d["hypothesis_formula"]
                        step_label = True
                    else:
                        # otherwise, we use the false hypothesis
                        hypothesis = f"\u00ac({d['hypothesis_formula']})"
                        step_label = False
                    
                    hypotehsis_filled = hypotehsis_template.format(
                        hypothesis=hypothesis
                    )

                    # in 50% of cases, we insert to the first step
                    if random.Random("insert hypothesis" + d["id"]
                                     ).random() < 0.5:
                        # insert hypothesis declaration at the beginning
                        d["proof_steps"].insert(0, hypotehsis_filled)
                        d["proof_step_correctness"].insert(0, step_label)
                        d["cot_steps"].insert(0, "")
                    # otherwise, we insert before the second last step
                    else:
                        target_step_idx = len(d["proof_steps"]) - 2
                        # insert hypothesis declaration before
                        # the second last step
                        d["proof_steps"].insert(
                            target_step_idx, hypotehsis_filled)
                        d["proof_step_correctness"].insert(
                            target_step_idx, step_label)
                        d["cot_steps"].insert(target_step_idx, "")


                # add premise declaration in 25% steps
                facts_dict = parse_formal_logic_facts(d["facts_formula"])
                for step_idx in range(len(d["proof_steps"])-1, -1, -1):
                    # we start from the last step to avoid index issues
                    # because we insert new steps before the current step

                    step_str = d["proof_steps"][step_idx]
                    facts_in_step = extract_facts(step_str)

                    # if there are no facts in the step, we skip it
                    if len(facts_in_step) == 0:
                        continue
                    
                    # insert premise declaration
                    if random.Random("premise" + d["id"] + str(step_idx)
                                     ).random() < 0.25:
                        premise_declaration = get_premise_declaration(
                            data_id=d["id"],
                            step_idx=step_idx,
                            facts_in_step=facts_in_step,
                            facts_dict=facts_dict,
                        )

                        # insert premise declaration before the step
                        d["proof_steps"].insert(step_idx, premise_declaration)
                        d["proof_step_correctness"].insert(step_idx, True)
                        d["cot_steps"].insert(step_idx, "")


            # add or merge non reasoning first steps in 50% of the cases
            if random.Random("non reasoning" + d["id"]).random() < 0.5:
                selected_non_reasoning_first_step = random.Random(
                    "select non reasoning" + d["id"]
                ).choice(non_reasoning_first_steps)

                # in 75% of cases, we simply add a non reasoning step
                # at the beginning
                if random.Random("add" + d["id"]).random() < 0.75:
                    # add non reasoning step at the beginning
                    d["proof_steps"].insert(
                        0, selected_non_reasoning_first_step)
                    d["proof_step_correctness"].insert(0, True)
                    d["cot_steps"].insert(0, "")
                # ohterwise, we merge the first two steps
                else:
                    # merge the first two steps
                    d["proof_steps"][0] = (
                        f"{selected_non_reasoning_first_step} " +
                        d["proof_steps"][0]
                    )

                    # we do not need to change the correctness of the first step
                    # because the non reasoning step does not influence
                    # the correctness of the first step
            
            # check the number of steps
            if len(d["proof_steps"]) != len(d["proof_step_correctness"]):
                raise ValueError(
                    f"Number of steps and correctness labels do not match. " \
                    f"data_id: {d['id']}, " \
                    f"num_steps: {len(d['proof_steps'])}, " \
                    f"num_labels: {len(d['proof_step_correctness'])}"
                )

            updated_error_label_instances.append(d)
        
        # save updated error labels
        output_path = error_labels_path.with_suffix(
            f".with_non_reasoning_steps.jsonl")
        with open(output_path, "w") as f:
            for d in updated_error_label_instances:
                f.write(json.dumps(d) + "\n")
        save_md5_hash(output_path)
        
        # get statistics
        stats = get_error_labels_stats(updated_error_label_instances)
        stats_path = output_path.with_suffix(f".stats.json")
        with open(stats_path, "w") as f:
            json.dump(stats, f, indent=4)


if __name__ == "__main__":
    main()
